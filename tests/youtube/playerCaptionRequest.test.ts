import { describe, expect, it } from "vitest";
import {
  asJson3CaptionUrl,
  findPreferredTokenizedCaption,
  findTokenizedCaptionUrl,
  isTokenizedCaptionRequest
} from "../../src/infrastructure/youtube/playerCaptionRequest";
import type { CaptionTrackSummary } from "../../src/shared/messages";

const englishTrack: CaptionTrackSummary = {
  baseUrl: "https://www.youtube.com/api/timedtext?v=video&lang=en&exp=xpe",
  languageCode: "en",
  languageName: "English",
  isAutoGenerated: false
};

describe("YouTube player caption request reuse", () => {
  it("recognizes token-bearing timedtext requests only", () => {
    expect(isTokenizedCaptionRequest(
      "https://www.youtube.com/api/timedtext?v=video&lang=en&potc=1&pot=proof"
    )).toBe(true);
    expect(isTokenizedCaptionRequest(englishTrack.baseUrl)).toBe(false);
    expect(isTokenizedCaptionRequest("https://www.youtube.com/watch?v=video&pot=proof")).toBe(false);
  });

  it("finds the latest tokenized request for the selected language", () => {
    const result = findTokenizedCaptionUrl([
      "https://www.youtube.com/api/timedtext?v=video&lang=en&pot=old",
      "https://www.youtube.com/api/timedtext?v=video&lang=de&pot=german",
      "https://www.youtube.com/api/timedtext?v=video&lang=en&pot=new"
    ], englishTrack);

    expect(new URL(result!).searchParams.get("pot")).toBe("new");
  });

  it("does not reuse a token from another language", () => {
    expect(findTokenizedCaptionUrl([
      "https://www.youtube.com/api/timedtext?v=video&lang=de&pot=proof"
    ], englishTrack)).toBeUndefined();
  });

  it("derives a caption track from the current player's request", () => {
    const candidate = findPreferredTokenizedCaption([
      "https://www.youtube.com/api/timedtext?v=old-video&lang=en&pot=old",
      "https://www.youtube.com/api/timedtext?v=current-video&lang=de&pot=german",
      "https://www.youtube.com/api/timedtext?v=current-video&lang=en&kind=asr&pot=proof"
    ], "current-video");

    expect(candidate?.url).toContain("pot=proof");
    expect(candidate?.track).toMatchObject({
      languageCode: "en",
      isAutoGenerated: true
    });
  });

  it("ignores tokenized requests belonging to a previous video", () => {
    expect(findPreferredTokenizedCaption([
      "https://www.youtube.com/api/timedtext?v=old-video&lang=en&pot=old"
    ], "current-video")).toBeUndefined();
  });

  it("preserves the token while selecting JSON3", () => {
    const result = new URL(asJson3CaptionUrl(
      "https://www.youtube.com/api/timedtext?v=video&lang=en&pot=proof&fmt=srv3"
    ));
    expect(result.searchParams.get("pot")).toBe("proof");
    expect(result.searchParams.get("fmt")).toBe("json3");
  });
});

