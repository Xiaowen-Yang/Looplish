import { describe, expect, it } from "vitest";
import {
  getCaptionTracks,
  selectPreferredCaptionTrack,
  withJson3Format
} from "../../src/infrastructure/youtube/playerResponse";

describe("YouTube player response", () => {
  const response = {
    captions: {
      playerCaptionsTracklistRenderer: {
        captionTracks: [
          {
            baseUrl: "https://www.youtube.com/api/timedtext?lang=en&kind=asr",
            languageCode: "en",
            kind: "asr",
            name: { simpleText: "English (auto-generated)" }
          },
          {
            baseUrl: "https://www.youtube.com/api/timedtext?lang=en-GB",
            languageCode: "en-GB",
            name: { runs: [{ text: "English" }, { text: " (UK)" }] }
          },
          {
            baseUrl: "https://www.youtube.com/api/timedtext?lang=de",
            languageCode: "de",
            name: { simpleText: "Deutsch" }
          }
        ]
      }
    }
  };

  it("extracts safe caption summaries", () => {
    const tracks = getCaptionTracks(response);
    expect(tracks).toHaveLength(3);
    expect(tracks[1]).toMatchObject({
      languageCode: "en-GB",
      languageName: "English (UK)",
      isAutoGenerated: false
    });
  });

  it("prefers manually authored English captions", () => {
    const track = selectPreferredCaptionTrack(getCaptionTracks(response));
    expect(track?.languageCode).toBe("en-GB");
    expect(track?.isAutoGenerated).toBe(false);
  });

  it("requests the JSON3 subtitle format without losing query values", () => {
    const url = new URL(withJson3Format("https://www.youtube.com/api/timedtext?lang=en"));
    expect(url.searchParams.get("lang")).toBe("en");
    expect(url.searchParams.get("fmt")).toBe("json3");
  });
});

