import { IDBFactory } from "fake-indexeddb";
import { beforeEach, describe, expect, it } from "vitest";
import type {
  AttemptRecord,
  ProgressRecord,
  VideoRecord
} from "../../src/domain/study/types";
import type { Sentence } from "../../src/domain/transcript/types";
import { IndexedDbStudyRepository } from "../../src/infrastructure/storage/indexedDbStudyRepository";

const video: VideoRecord = {
  videoId: "abc123",
  title: "Test video",
  channel: "Test channel",
  duration: 120,
  languageCode: "en",
  languageName: "English",
  isAutoGenerated: false,
  lastStudiedAt: 1000
};

const sentences: Sentence[] = [
  {
    id: "abc123:0",
    videoId: "abc123",
    order: 0,
    startTime: 0,
    endTime: 2,
    text: "Hello world."
  },
  {
    id: "abc123:1",
    videoId: "abc123",
    order: 1,
    startTime: 2,
    endTime: 4,
    text: "Welcome to Looplish."
  }
];

describe("IndexedDbStudyRepository", () => {
  let repository: IndexedDbStudyRepository;

  beforeEach(() => {
    repository = new IndexedDbStudyRepository(
      new IDBFactory(),
      `looplish-test-${crypto.randomUUID()}`
    );
  });

  it("saves and restores a transcript in sentence order", async () => {
    await repository.saveTranscript(video, [...sentences].reverse());

    const study = await repository.getStudy(video.videoId);

    expect(study?.video).toEqual(video);
    expect(study?.transcript.sentences).toEqual(sentences);
  });

  it("replaces stale sentences when a transcript is refreshed", async () => {
    await repository.saveTranscript(video, sentences);
    await repository.saveTranscript(video, [sentences[1]!]);

    const study = await repository.getStudy(video.videoId);
    expect(study?.transcript.sentences).toEqual([sentences[1]]);
  });

  it("stores attempts by sentence", async () => {
    const attempt: AttemptRecord = {
      id: "attempt-1",
      videoId: video.videoId,
      sentenceId: sentences[0]!.id,
      typedText: "hello word",
      accuracy: 0.5,
      createdAt: 2000
    };

    await repository.saveAttempt(attempt);
    expect(await repository.getAttempts(sentences[0]!.id)).toEqual([attempt]);
  });

  it("stores progress per video", async () => {
    const progress: ProgressRecord = {
      videoId: video.videoId,
      currentSentenceOrder: 1,
      playbackRate: 0.85,
      completedSentenceIds: [sentences[0]!.id],
      updatedAt: 3000
    };

    await repository.saveProgress(progress);
    expect(await repository.getProgress(video.videoId)).toEqual(progress);
  });
});

