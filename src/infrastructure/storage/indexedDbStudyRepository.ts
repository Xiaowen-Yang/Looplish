import type {
  AttemptRecord,
  ProgressRecord,
  SavedStudy,
  StudyRepository,
  VideoRecord
} from "../../domain/study/types";
import type { Sentence } from "../../domain/transcript/types";
import { APP_CONFIG } from "../../shared/config";
import { STORAGE_SCHEMA } from "./schema";

function requestAsPromise<T>(request: IDBRequest<T>): Promise<T> {
  return new Promise((resolve, reject) => {
    request.addEventListener("success", () => resolve(request.result));
    request.addEventListener("error", () => reject(request.error));
  });
}

function transactionDone(transaction: IDBTransaction): Promise<void> {
  return new Promise((resolve, reject) => {
    transaction.addEventListener("complete", () => resolve());
    transaction.addEventListener("abort", () => reject(transaction.error));
    transaction.addEventListener("error", () => reject(transaction.error));
  });
}

export class IndexedDbStudyRepository implements StudyRepository {
  private databasePromise?: Promise<IDBDatabase>;

  constructor(
    private readonly factory: IDBFactory = indexedDB,
    private readonly databaseName: string = APP_CONFIG.database.name
  ) {}

  async saveTranscript(video: VideoRecord, sentences: Sentence[]): Promise<void> {
    const database = await this.getDatabase();
    const transaction = database.transaction([
      STORAGE_SCHEMA.stores.videos,
      STORAGE_SCHEMA.stores.sentences
    ], "readwrite");
    const videos = transaction.objectStore(STORAGE_SCHEMA.stores.videos);
    const sentenceStore = transaction.objectStore(STORAGE_SCHEMA.stores.sentences);
    const sentenceIndex = sentenceStore.index(STORAGE_SCHEMA.indexes.sentencesByVideo);

    videos.put(video);
    const oldKeys = await requestAsPromise(sentenceIndex.getAllKeys(video.videoId));
    oldKeys.forEach((key) => sentenceStore.delete(key));
    sentences.forEach((sentence) => sentenceStore.put(sentence));
    await transactionDone(transaction);
  }

  async getStudy(videoId: string): Promise<SavedStudy | undefined> {
    const database = await this.getDatabase();
    const transaction = database.transaction([
      STORAGE_SCHEMA.stores.videos,
      STORAGE_SCHEMA.stores.sentences
    ], "readonly");
    const videoRequest = transaction
      .objectStore(STORAGE_SCHEMA.stores.videos)
      .get(videoId) as IDBRequest<VideoRecord | undefined>;
    const sentenceRequest = transaction
      .objectStore(STORAGE_SCHEMA.stores.sentences)
      .index(STORAGE_SCHEMA.indexes.sentencesByVideo)
      .getAll(videoId) as IDBRequest<Sentence[]>;
    const [video, sentences] = await Promise.all([
      requestAsPromise(videoRequest),
      requestAsPromise(sentenceRequest)
    ]);
    await transactionDone(transaction);

    if (!video) {
      return undefined;
    }

    return {
      video,
      transcript: {
        videoId,
        languageCode: video.languageCode,
        languageName: video.languageName,
        isAutoGenerated: video.isAutoGenerated,
        sentences: sentences.sort((left, right) => left.order - right.order)
      }
    };
  }

  async saveAttempt(attempt: AttemptRecord): Promise<void> {
    const database = await this.getDatabase();
    const transaction = database.transaction(
      STORAGE_SCHEMA.stores.attempts,
      "readwrite"
    );
    transaction.objectStore(STORAGE_SCHEMA.stores.attempts).put(attempt);
    await transactionDone(transaction);
  }

  async getAttempts(sentenceId: string): Promise<AttemptRecord[]> {
    const database = await this.getDatabase();
    const transaction = database.transaction(STORAGE_SCHEMA.stores.attempts, "readonly");
    const request = transaction
      .objectStore(STORAGE_SCHEMA.stores.attempts)
      .index(STORAGE_SCHEMA.indexes.attemptsBySentence)
      .getAll(sentenceId) as IDBRequest<AttemptRecord[]>;
    const attempts = await requestAsPromise(request);
    await transactionDone(transaction);
    return attempts.sort((left, right) => left.createdAt - right.createdAt);
  }

  async saveProgress(progress: ProgressRecord): Promise<void> {
    const database = await this.getDatabase();
    const transaction = database.transaction(
      STORAGE_SCHEMA.stores.progress,
      "readwrite"
    );
    transaction.objectStore(STORAGE_SCHEMA.stores.progress).put(progress);
    await transactionDone(transaction);
  }

  async getProgress(videoId: string): Promise<ProgressRecord | undefined> {
    const database = await this.getDatabase();
    const transaction = database.transaction(STORAGE_SCHEMA.stores.progress, "readonly");
    const request = transaction
      .objectStore(STORAGE_SCHEMA.stores.progress)
      .get(videoId) as IDBRequest<ProgressRecord | undefined>;
    const progress = await requestAsPromise(request);
    await transactionDone(transaction);
    return progress;
  }

  close(): void {
    void this.databasePromise?.then((database) => database.close());
    this.databasePromise = undefined;
  }

  private getDatabase(): Promise<IDBDatabase> {
    this.databasePromise ??= this.openDatabase();
    return this.databasePromise;
  }

  private openDatabase(): Promise<IDBDatabase> {
    return new Promise((resolve, reject) => {
      const request = this.factory.open(
        this.databaseName,
        APP_CONFIG.database.version
      );

      request.addEventListener("upgradeneeded", () => {
        const database = request.result;

        if (!database.objectStoreNames.contains(STORAGE_SCHEMA.stores.videos)) {
          database.createObjectStore(STORAGE_SCHEMA.stores.videos, {
            keyPath: "videoId"
          });
        }

        if (!database.objectStoreNames.contains(STORAGE_SCHEMA.stores.sentences)) {
          const sentences = database.createObjectStore(
            STORAGE_SCHEMA.stores.sentences,
            { keyPath: "id" }
          );
          sentences.createIndex(
            STORAGE_SCHEMA.indexes.sentencesByVideo,
            "videoId",
            { unique: false }
          );
        }

        if (!database.objectStoreNames.contains(STORAGE_SCHEMA.stores.attempts)) {
          const attempts = database.createObjectStore(
            STORAGE_SCHEMA.stores.attempts,
            { keyPath: "id" }
          );
          attempts.createIndex(
            STORAGE_SCHEMA.indexes.attemptsBySentence,
            "sentenceId",
            { unique: false }
          );
        }

        if (!database.objectStoreNames.contains(STORAGE_SCHEMA.stores.progress)) {
          database.createObjectStore(STORAGE_SCHEMA.stores.progress, {
            keyPath: "videoId"
          });
        }
      });

      request.addEventListener("success", () => resolve(request.result));
      request.addEventListener("error", () => reject(request.error));
      request.addEventListener("blocked", () => {
        reject(new Error("Looplish database upgrade was blocked by another tab."));
      });
    });
  }
}

