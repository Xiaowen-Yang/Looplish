import type { CaptionTrackSummary } from "../../shared/messages";
import { withJson3Format } from "./playerResponse";

export interface TokenizedCaptionCandidate {
  url: string;
  track: CaptionTrackSummary;
}

function parseUrl(value: string): URL | undefined {
  try {
    return new URL(value);
  } catch {
    return undefined;
  }
}

export function isTokenizedCaptionRequest(value: string): boolean {
  const url = parseUrl(value);
  if (!url || !url.pathname.includes("/api/timedtext")) {
    return false;
  }

  return url.searchParams.has("pot") || url.searchParams.has("potc");
}

export function findTokenizedCaptionUrl(
  resourceUrls: string[],
  track: CaptionTrackSummary
): string | undefined {
  const preferredLanguage = track.languageCode.toLowerCase();

  return [...resourceUrls]
    .reverse()
    .filter(isTokenizedCaptionRequest)
    .map(parseUrl)
    .find((url) => {
      const requestLanguage = url?.searchParams.get("lang")?.toLowerCase();
      return requestLanguage === preferredLanguage;
    })
    ?.toString();
}

export function findPreferredTokenizedCaption(
  resourceUrls: string[],
  videoId: string,
  preferredLanguage = "en"
): TokenizedCaptionCandidate | undefined {
  const preferred = preferredLanguage.toLowerCase();

  for (const value of [...resourceUrls].reverse()) {
    if (!isTokenizedCaptionRequest(value)) {
      continue;
    }

    const url = parseUrl(value);
    const languageCode = url?.searchParams.get("lang");
    const requestVideoId = url?.searchParams.get("v");
    if (
      !url
      || !languageCode
      || requestVideoId !== videoId
      || !languageCode.toLowerCase().startsWith(preferred)
    ) {
      continue;
    }

    const isAutoGenerated = url.searchParams.get("kind") === "asr"
      || url.searchParams.get("caps") === "asr";
    return {
      url: url.toString(),
      track: {
        baseUrl: url.toString(),
        languageCode,
        languageName: languageCode.toLowerCase().startsWith("en")
          ? `English (${isAutoGenerated ? "auto-generated" : languageCode})`
          : languageCode,
        isAutoGenerated
      }
    };
  }

  return undefined;
}

export function getCaptionResourceUrls(
  entries: PerformanceEntry[] = performance.getEntriesByType("resource")
): string[] {
  return entries.map((entry) => entry.name);
}

export function asJson3CaptionUrl(value: string): string {
  return withJson3Format(value);
}

