import type { CaptionTrackSummary } from "../../shared/messages";

interface RawCaptionTrack {
  baseUrl?: string;
  languageCode?: string;
  kind?: string;
  name?: {
    simpleText?: string;
    runs?: Array<{ text?: string }>;
  };
}

interface PlayerResponseShape {
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: RawCaptionTrack[];
    };
  };
}

export function getCaptionTracks(value: unknown): CaptionTrackSummary[] {
  const response = value as PlayerResponseShape | undefined;
  const tracks = response?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];

  return tracks.flatMap((track) => {
    if (!track.baseUrl || !track.languageCode) {
      return [];
    }

    const languageName = track.name?.simpleText
      ?? track.name?.runs?.map((run) => run.text ?? "").join("")
      ?? track.languageCode;

    return [{
      baseUrl: track.baseUrl,
      languageCode: track.languageCode,
      languageName,
      isAutoGenerated: track.kind === "asr"
    }];
  });
}

export function selectPreferredCaptionTrack(
  tracks: CaptionTrackSummary[],
  preferredLanguage = "en"
): CaptionTrackSummary | undefined {
  return [...tracks].sort((left, right) => {
    const score = (track: CaptionTrackSummary): number => {
      const isPreferred = track.languageCode.toLowerCase().startsWith(preferredLanguage);
      return (isPreferred ? 2 : 0) + (track.isAutoGenerated ? 0 : 1);
    };

    return score(right) - score(left);
  })[0];
}

export function withJson3Format(baseUrl: string): string {
  const url = new URL(baseUrl);
  url.searchParams.set("fmt", "json3");
  return url.toString();
}

