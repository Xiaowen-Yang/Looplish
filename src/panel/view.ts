import type { ComparisonResult } from "../domain/comparison/types";
import type { Sentence } from "../domain/transcript/types";
import { COPY } from "./copy";

function requiredElement<T extends HTMLElement>(selector: string): T {
  const element = document.querySelector<T>(selector);
  if (!element) {
    throw new Error(`Missing panel element: ${selector}`);
  }
  return element;
}

export class PanelView {
  readonly answerInput = requiredElement<HTMLTextAreaElement>("#answer-input");
  readonly checkButton = requiredElement<HTMLButtonElement>("#check-button");
  readonly replayButton = requiredElement<HTMLButtonElement>("#replay-button");
  readonly toggleButton = requiredElement<HTMLButtonElement>("#toggle-button");
  readonly previousButton = requiredElement<HTMLButtonElement>("#previous-button");
  readonly nextButton = requiredElement<HTMLButtonElement>("#next-button");
  readonly retryButton = requiredElement<HTMLButtonElement>("#retry-button");
  readonly rateSelect = requiredElement<HTMLSelectElement>("#rate-select");

  private readonly loading = requiredElement<HTMLElement>("#loading-state");
  private readonly error = requiredElement<HTMLElement>("#error-state");
  private readonly practice = requiredElement<HTMLElement>("#practice-state");
  private readonly errorMessage = requiredElement<HTMLElement>("#error-message");
  private readonly videoTitle = requiredElement<HTMLElement>("#video-title");
  private readonly videoMeta = requiredElement<HTMLElement>("#video-meta");
  private readonly position = requiredElement<HTMLElement>("#position");
  private readonly progress = requiredElement<HTMLProgressElement>("#progress");
  private readonly result = requiredElement<HTMLElement>("#result");
  private readonly score = requiredElement<HTMLElement>("#score");
  private readonly diff = requiredElement<HTMLElement>("#diff");
  private readonly reference = requiredElement<HTMLElement>("#reference");
  private readonly localStatus = requiredElement<HTMLElement>("#local-status");

  showLoading(): void {
    this.loading.hidden = false;
    this.error.hidden = true;
    this.practice.hidden = true;
  }

  showError(message: string): void {
    this.loading.hidden = true;
    this.error.hidden = false;
    this.practice.hidden = true;
    this.errorMessage.textContent = message;
  }

  showPractice(details: {
    title: string;
    languageName: string;
    isAutoGenerated: boolean;
    sentence: Sentence;
    order: number;
    total: number;
    completedCount: number;
    playbackRate: number;
  }): void {
    this.loading.hidden = true;
    this.error.hidden = true;
    this.practice.hidden = false;
    this.videoTitle.textContent = details.title;
    this.videoMeta.textContent = `${details.languageName}${details.isAutoGenerated ? " · 自动字幕" : " · 人工字幕"}`;
    this.position.textContent = `第 ${details.order + 1} / ${details.total} 句 · 已完成 ${details.completedCount}`;
    this.progress.max = Math.max(details.total, 1);
    this.progress.value = details.order + 1;
    this.rateSelect.value = String(details.playbackRate);
    this.previousButton.disabled = details.order === 0;
    this.nextButton.disabled = details.order === details.total - 1;
    this.localStatus.textContent = COPY.savedLocally;
    this.resetAnswer();
  }

  showComparison(comparison: ComparisonResult, referenceText: string): void {
    this.result.hidden = false;
    this.score.textContent = `正确率 ${Math.round(comparison.accuracy * 100)}% · ${comparison.correctWords}/${comparison.expectedWords} 词`;
    this.diff.replaceChildren(...comparison.diff.map((token) => {
      const element = document.createElement("span");
      element.className = `diff-token diff-token--${token.kind}`;
      element.textContent = token.value;
      return element;
    }));
    this.reference.textContent = referenceText;
  }

  resetAnswer(): void {
    this.answerInput.value = "";
    this.answerInput.placeholder = COPY.answerPlaceholder;
    this.result.hidden = true;
    this.diff.replaceChildren();
    this.reference.textContent = "";
    this.answerInput.focus();
  }

  setStorageWarning(show: boolean): void {
    this.localStatus.textContent = show ? COPY.storageWarning : COPY.savedLocally;
  }
}

