import { StudySession } from "../application/studySession";
import { compareTranscript } from "../domain/comparison/compare";
import type { VideoRecord } from "../domain/study/types";
import { IndexedDbStudyRepository } from "../infrastructure/storage/indexedDbStudyRepository";
import { requestPersistentStorage } from "../infrastructure/storage/persistence";
import type { PageStudyPayload } from "../shared/messages";
import { loadPageStudy, sendToActiveTab } from "./chromeGateway";
import { COPY } from "./copy";
import { PanelView } from "./view";

const view = new PanelView();
const repository = new IndexedDbStudyRepository();
let study: PageStudyPayload | undefined;
let session: StudySession | undefined;

function createVideoRecord(payload: PageStudyPayload): VideoRecord {
  return {
    videoId: payload.videoId,
    title: payload.title,
    channel: payload.channel,
    duration: payload.duration,
    languageCode: payload.caption.languageCode,
    languageName: payload.caption.languageName,
    isAutoGenerated: payload.caption.isAutoGenerated,
    lastStudiedAt: Date.now()
  };
}

function render(): void {
  const sentence = session?.current;
  if (!study || !session || !sentence) {
    view.showError("这个字幕轨道没有可练习的句子。");
    return;
  }

  view.showPractice({
    title: study.title,
    languageName: study.caption.languageName,
    isAutoGenerated: study.caption.isAutoGenerated,
    sentence,
    order: session.currentOrder,
    total: session.sentences.length,
    completedCount: session.completedCount,
    playbackRate: session.playbackRate
  });
}

async function persistProgress(): Promise<void> {
  if (session) {
    await repository.saveProgress(session.toProgress());
  }
}

async function replayCurrent(): Promise<void> {
  const sentence = session?.current;
  if (!sentence || !session) {
    return;
  }
  await sendToActiveTab<void>({
    type: "PLAY_SENTENCE",
    startTime: sentence.startTime,
    endTime: sentence.endTime,
    playbackRate: session.playbackRate
  });
}

async function move(offset: number): Promise<void> {
  if (!session) {
    return;
  }
  session.move(offset);
  await persistProgress();
  render();
  await replayCurrent();
}

async function checkAnswer(): Promise<void> {
  const sentence = session?.current;
  const typedText = view.answerInput.value.trim();
  if (!study || !session || !sentence) {
    return;
  }
  if (!typedText) {
    view.answerInput.placeholder = COPY.noAnswer;
    view.answerInput.focus();
    return;
  }

  const comparison = compareTranscript(sentence.text, typedText);
  session.completeCurrent();
  await Promise.all([
    repository.saveAttempt({
      id: crypto.randomUUID(),
      videoId: study.videoId,
      sentenceId: sentence.id,
      typedText,
      accuracy: comparison.accuracy,
      createdAt: Date.now()
    }),
    persistProgress()
  ]);
  view.showComparison(comparison, sentence.text);
}

async function initialize(): Promise<void> {
  view.showLoading();
  try {
    study = await loadPageStudy();
    await repository.saveTranscript(createVideoRecord(study), study.sentences);
    const progress = await repository.getProgress(study.videoId);
    session = new StudySession(study.videoId, study.sentences, progress);
    render();
    view.setStorageWarning(!(await requestPersistentStorage()));
  } catch (error) {
    view.showError(error instanceof Error ? error.message : "Looplish 初始化失败。");
  }
}

view.replayButton.addEventListener("click", () => void replayCurrent());
view.toggleButton.addEventListener("click", () => {
  void sendToActiveTab<void>({ type: "TOGGLE_PLAYBACK" });
});
view.previousButton.addEventListener("click", () => void move(-1));
view.nextButton.addEventListener("click", () => void move(1));
view.checkButton.addEventListener("click", () => void checkAnswer());
view.retryButton.addEventListener("click", () => void initialize());
view.rateSelect.addEventListener("change", () => {
  if (!session) {
    return;
  }
  session.setPlaybackRate(Number(view.rateSelect.value));
  void persistProgress();
});

document.addEventListener("keydown", (event) => {
  const modifier = event.altKey;
  if (modifier && event.code === "Space") {
    event.preventDefault();
    void replayCurrent();
  } else if (modifier && event.code === "ArrowLeft") {
    event.preventDefault();
    void move(-1);
  } else if (modifier && event.code === "ArrowRight") {
    event.preventDefault();
    void move(1);
  } else if ((event.ctrlKey || event.metaKey) && event.key === "Enter") {
    event.preventDefault();
    void checkAnswer();
  }
});

