import type { Sentence, Transcript } from "../transcript/types";

export interface VideoRecord {
  videoId: string;
  title: string;
  channel: string;
  duration: number;
  languageCode: string;
  languageName: string;
  isAutoGenerated: boolean;
  lastStudiedAt: number;
}

export interface AttemptRecord {
  id: string;
  videoId: string;
  sentenceId: string;
  typedText: string;
  accuracy: number;
  createdAt: number;
}

export interface ProgressRecord {
  videoId: string;
  currentSentenceOrder: number;
  playbackRate: number;
  completedSentenceIds: string[];
  updatedAt: number;
}

export interface SavedStudy {
  video: VideoRecord;
  transcript: Transcript;
}

export interface StudyRepository {
  saveTranscript(video: VideoRecord, sentences: Sentence[]): Promise<void>;
  getStudy(videoId: string): Promise<SavedStudy | undefined>;
  saveAttempt(attempt: AttemptRecord): Promise<void>;
  getAttempts(sentenceId: string): Promise<AttemptRecord[]>;
  saveProgress(progress: ProgressRecord): Promise<void>;
  getProgress(videoId: string): Promise<ProgressRecord | undefined>;
}

