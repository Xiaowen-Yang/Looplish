import type { Sentence, YouTubeTimedText } from "../domain/transcript/types";

export const BRIDGE_CHANNEL = "looplish-youtube-bridge";

export interface CaptionTrackSummary {
  baseUrl: string;
  languageCode: string;
  languageName: string;
  isAutoGenerated: boolean;
}

export interface PageStudyPayload {
  videoId: string;
  title: string;
  channel: string;
  duration: number;
  caption: CaptionTrackSummary;
  sentences: Sentence[];
}

export type ExtensionRequest =
  | { type: "GET_PAGE_STUDY" }
  | { type: "PLAY_SENTENCE"; startTime: number; endTime: number; playbackRate: number }
  | { type: "TOGGLE_PLAYBACK" }
  | { type: "PAUSE_PLAYBACK" };

export type ExtensionResponse<T = unknown> =
  | { ok: true; data: T }
  | { ok: false; error: string };

export interface BridgeRequestMessage {
  channel: typeof BRIDGE_CHANNEL;
  direction: "request";
  requestId: string;
}

export interface BridgeResponseMessage {
  channel: typeof BRIDGE_CHANNEL;
  direction: "response";
  requestId: string;
  payload?: {
    caption: CaptionTrackSummary;
    timedText: YouTubeTimedText;
  };
  error?: string;
}

